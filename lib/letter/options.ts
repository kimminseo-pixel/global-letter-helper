export type ParsedDate =
  | { kind: "empty" }
  | { kind: "invalid" }
  | { kind: "ok"; year: number; month: number; day: number; korean: string };

/**
 * 날짜 입력을 인식한다. 20250212, 2025-02-12, 2025.2.12, 2025/2/12 모두 같은 날짜로 본다.
 * 월·일이 실제 달력에 없으면 invalid.
 */
export function parseDateInput(text: string): ParsedDate {
  const raw = text.trim();
  if (raw === "") return { kind: "empty" };

  const compact = /^(\d{4})(\d{2})(\d{2})$/.exec(raw);
  const separated = /^(\d{4})[-./\s]+(\d{1,2})[-./\s]+(\d{1,2})$/.exec(raw);
  const match = compact ?? separated;
  if (!match) return { kind: "invalid" };
  const y = Number(match[1]);
  const m = Number(match[2]);
  const d = Number(match[3]);

  const date = new Date(y, m - 1, d);
  if (
    date.getFullYear() !== y ||
    date.getMonth() !== m - 1 ||
    date.getDate() !== d
  ) {
    return { kind: "invalid" };
  }
  return { kind: "ok", year: y, month: m, day: d, korean: `${y}년 ${m}월 ${d}일` };
}
